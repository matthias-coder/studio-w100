const test=require('node:test'),assert=require('node:assert/strict');
const {load,newProject}=require('./harness');
test('sprint bar renders presets and points',()=>{const {run}=load({ui:true});newProject(run);
  const h=run('sprintBar()');assert.match(h,/Ausgewogen/);assert.match(h,/Meilenstein-Ziel/);assert.match(h,/Punkte/);});
test('crunch button disabled at moral 1',()=>{const {run}=load({ui:true});newProject(run);
  run('S.res.moral=1');assert.match(run('sprintBar()'),/data-crunch[^>]*disabled/);});
test('crunch button disabled on a contract step',()=>{const {run}=load({ui:true});newProject(run);
  run('S.res.moral=8;S.contractStep=S.round');const h=run('sprintBar()');
  assert.match(h,/data-crunch[^>]*disabled/);assert.match(h,/Auftragsarbeit/);});
test('milestone screen lists Ist and Soll',()=>{const {run}=load({ui:true});newProject(run);
  run(`S.msResult=msCheck('vs');S.msResult.notes=['x'];S.screen='milestone'`);
  const h=run(`(()=>{const m={innerHTML:'',className:''};renderMilestone(m);return m.innerHTML})()`);
  assert.match(h,/Vertical Slice/);assert.match(h,/Soll/);assert.match(h,/id="msNext"/);});
test('milestone screen is an active screen',()=>{const {run}=load({ui:true});assert.ok(run(`ACTIVE.includes('milestone')`));});
test('sheet panel shows next milestone',()=>{const {run}=load({ui:true});newProject(run);
  const h=run('msBlock()');assert.match(h,/Vertical Slice/);assert.match(h,/Soll/);
  run(`S.msDone=MILESTONES.map(m=>m.id)`);assert.equal(run('msBlock()'),'');});
test('fine-tune step sets custom focus and clamps',()=>{const {run}=load({ui:true});newProject(run);
  run(`sprintTune('gp',5)`);assert.equal(run('S.sprint.focus'),'custom');
  const a=run('sprintAlloc().gp'),b=run('S.sprint.custom.gp');assert.ok(b>=0&&b<=100);assert.ok(a>=0);
  run(`for(let i=0;i<40;i++)sprintTune('gp',5)`);assert.equal(run('S.sprint.custom.gp'),100);
  run(`for(let i=0;i<40;i++)sprintTune('gp',-5)`);assert.equal(run('S.sprint.custom.gp'),0);});
